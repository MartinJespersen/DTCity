param(
    [Parameter(Mandatory = $true)][string]$SourceFile,
    [Parameter(Mandatory = $true)][ValidateRange(1, 2147483647)][int]$Line,
    [Parameter(Mandatory = $true)][string]$Executable,
    [string]$Debugger = 'C:/repos/raddebugger/build/raddbg.exe'
)

$ErrorActionPreference = 'Stop'
$sourcePath = (Resolve-Path -LiteralPath $SourceFile).Path.Replace('\', '/')
$targetPath = (Resolve-Path -LiteralPath $Executable).Path
$debuggerPath = (Resolve-Path -LiteralPath $Debugger).Path
$targetDirectory = Split-Path -Parent $targetPath

# Separate projects keep each launch's breakpoint independent of existing sessions.
$sessionDirectory = Join-Path $targetDirectory 'raddebugger'
New-Item -ItemType Directory -Path $sessionDirectory -Force | Out-Null
$projectPath = Join-Path $sessionDirectory ('cursor-' + [guid]::NewGuid().ToString('N') + '.raddbg_project')
$projectText = "// Generated by the Zed launch-and-break task.`n"
[System.IO.File]::WriteAllText($projectPath, $projectText, [System.Text.UTF8Encoding]::new($false))

# The debugger is intentionally visible: this task opens an interactive session.
$debuggerProcess = Start-Process -FilePath $debuggerPath -WorkingDirectory $targetDirectory -ArgumentList @(
    ('--project:"' + $projectPath + '"'),
    ('"' + $targetPath + '"')
) -PassThru

# Start paused, then send commands to this specific instance in order.
$deadline = [DateTime]::UtcNow.AddSeconds(30)
do {
    $debuggerProcess.Refresh()
    if ($debuggerProcess.HasExited) { throw 'RAD Debugger exited during startup.' }
    if ($debuggerProcess.MainWindowHandle -ne 0) { break }
    if ([DateTime]::UtcNow -ge $deadline) { throw 'Timed out waiting for RAD Debugger to start.' }
    Start-Sleep -Milliseconds 100
} while ($true)

$instanceArgument = '--pid:' + $debuggerProcess.Id
$location = "${sourcePath}:${Line}:1"
# The window can appear before the IPC receiver is ready. Wait for a state reply.
# Piping GUI executable output makes PowerShell wait for each IPC sender to exit.
do {
    $reply = & $debuggerPath --ipc $instanceArgument state | Out-String
    if ($LASTEXITCODE -eq 0 -and $reply -match 'state:') { break }
    $debuggerProcess.Refresh()
    if ($debuggerProcess.HasExited -or [DateTime]::UtcNow -ge $deadline) {
        throw 'RAD Debugger IPC did not become ready.'
    }
    Start-Sleep -Milliseconds 200
} while ($true)
& $debuggerPath --ipc $instanceArgument add_breakpoint $location | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Could not set the breakpoint.' }
& $debuggerPath --ipc $instanceArgument find_code_location $location | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Could not navigate to the breakpoint.' }
& $debuggerPath --ipc $instanceArgument run | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Could not run the target.' }
Write-Output "RAD Debugger PID: $($debuggerProcess.Id); breakpoint: ${sourcePath}:${Line}"
